use std::path::Path;
use std::process::{Child, Command, Output, Stdio};
use std::time::Duration;

const SCHEMA: &str = r#"
tables:
  - id: 1
    name: users
    columns:
      - { id: 1, name: id, type: string, pk: true }
"#;

struct Server(Child);

impl Drop for Server {
    fn drop(&mut self) {
        let _ = self.0.kill();
        let _ = self.0.wait();
    }
}

#[tokio::test]
async fn generated_cli_drives_the_schema_workflow_over_http() {
    let directory = tempfile::tempdir().unwrap();
    let schema = directory.path().join("rad.schema.yaml");
    let config = directory.path().join("rad.config.yaml");
    std::fs::write(&schema, SCHEMA).unwrap();

    let listener = std::net::TcpListener::bind("127.0.0.1:0").unwrap();
    let port = listener.local_addr().unwrap().port();
    drop(listener);
    std::fs::write(
        &config,
        format!(
            "database_url: rad://127.0.0.1:{port}\ngenerate:\n  - language: go\n    output: generated\n    package: db\n"
        ),
    )
    .unwrap();

    let binary = env!("CARGO_BIN_EXE_rad");
    let child = Command::new(binary)
        .args([
            "serve",
            "--addr",
            &format!("127.0.0.1:{port}"),
            "--storage",
            "memory",
            "--storage-path",
            "cli-workflow",
            "--catalog-mode",
            "schema",
        ])
        .stdout(Stdio::inherit())
        .stderr(Stdio::inherit())
        .spawn()
        .unwrap();
    let mut server = Server(child);
    wait_until_ready(port, &mut server.0).await;

    let diff = run(binary, &config, &schema, &["diff", "--format", "json"]);
    assert_success(&diff);
    let body: serde_json::Value = serde_json::from_slice(&diff.stdout).unwrap();
    assert_eq!(body["changes"].as_array().unwrap().len(), 1);

    let migrate = run(binary, &config, &schema, &["migrate", "--output", "json"]);
    assert_success(&migrate);
    let migrate_body: serde_json::Value = serde_json::from_slice(&migrate.stdout).unwrap();
    assert_eq!(migrate_body["state"], "ready");
    assert_eq!(migrate_body["schema_version"], 1);
    assert_eq!(migrate_body["generated"].as_array().unwrap().len(), 1);
    assert!(
        migrate_body["snapshot"]
            .as_str()
            .unwrap()
            .ends_with("rad.state/changelog/00000001.rad.schema.yaml")
    );
    assert!(directory.path().join("rad.state/schema.lock.json").exists());

    let generated = directory.path().join("generated");
    let first_generate = run_generate(binary, &schema, &generated);
    assert_success(&first_generate);
    let generated_client = generated.join("rad_client_gen.go");
    let first_source = std::fs::read(&generated_client).unwrap();
    assert!(first_source.starts_with(b"// Code generated by rad generate. DO NOT EDIT.\n"));
    assert!(
        first_source
            .windows(b"const SchemaVersion uint64 = 1".len())
            .any(|window| { window == b"const SchemaVersion uint64 = 1" })
    );
    let second_generate = run_generate(binary, &schema, &generated);
    assert_success(&second_generate);
    assert_eq!(std::fs::read(&generated_client).unwrap(), first_source);

    let status = run(binary, &config, &schema, &["status"]);
    assert_success(&status);
    assert!(String::from_utf8_lossy(&status.stdout).contains("Status: synchronized"));
    let json_status = run(binary, &config, &schema, &["status", "--output", "json"]);
    assert_success(&json_status);
    let status_body: serde_json::Value = serde_json::from_slice(&json_status.stdout).unwrap();
    assert_eq!(status_body["status"], "synchronized");
    assert_eq!(status_body["desired_changes"], 0);
    assert_eq!(status_body["generated_clients"][0]["state"], "synchronized");

    let inserted = reqwest::Client::new()
        .post(format!("http://127.0.0.1:{port}/execute"))
        .json(&serde_json::json!({
            "statements": [{
                "name": "insert-user",
                "kind": "create",
                "table": "users",
                "relation": {
                    "nodes": {
                        "row": {
                            "kind": "rows",
                            "scope": "literal",
                            "columns": [{"name": "id", "type": "text"}],
                            "rows": [["user-1"]]
                        }
                    },
                    "root": {"node": "row", "cardinality": "many"}
                }
            }]
        }))
        .send()
        .await
        .unwrap();
    assert!(inserted.status().is_success());

    std::fs::write(&schema, SCHEMA.replace("users", "accounts")).unwrap();
    let refused_generate = run_generate(binary, &schema, &generated);
    assert_failure(&refused_generate);
    assert!(
        String::from_utf8_lossy(&refused_generate.stderr)
            .contains("differs from accepted schema version 1")
    );
    let refused_pull = run(binary, &config, &schema, &["pull"]);
    assert_failure(&refused_pull);
    assert!(
        String::from_utf8_lossy(&refused_pull.stderr).contains("contains local schema changes")
    );
    assert!(
        std::fs::read_to_string(&schema)
            .unwrap()
            .contains("name: accounts")
    );

    let pull = run(binary, &config, &schema, &["pull", "--force"]);
    assert_success(&pull);
    assert!(String::from_utf8_lossy(&pull.stdout).contains("Pulled schema version 1"));
    assert!(
        std::fs::read_to_string(&schema)
            .unwrap()
            .contains("name: users")
    );
    let backups = std::fs::read_dir(directory.path().join("rad.state/backups"))
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .collect::<Vec<_>>();
    assert_eq!(backups.len(), 1);
    assert!(
        std::fs::read_to_string(&backups[0])
            .unwrap()
            .contains("name: accounts")
    );

    std::fs::write(&schema, "tables: []\n").unwrap();
    let destructive = run(
        binary,
        &config,
        &schema,
        &["migrate", "--non-interactive", "--output", "json"],
    );
    assert_failure(&destructive);
    assert!(destructive.stdout.is_empty());
    let error: serde_json::Value = serde_json::from_slice(&destructive.stderr).unwrap();
    assert_eq!(error["error"]["code"], "confirmation_required");

    let indexed = SCHEMA.replace(
        "    columns:\n",
        "    indexes:\n      - { name: users_id_idx, columns: [id] }\n    columns:\n",
    );
    std::fs::write(&schema, indexed).unwrap();
    let online = run(binary, &config, &schema, &["migrate"]);
    assert_success(&online);
    let online_stdout = String::from_utf8_lossy(&online.stdout);
    assert!(
        online_stdout.contains("Waiting for 1 online schema transition"),
        "{online_stdout}"
    );
    assert!(
        online_stdout.contains("Schema version 2 committed"),
        "{online_stdout}"
    );

    let lock: serde_json::Value = serde_json::from_slice(
        &std::fs::read(directory.path().join("rad.state/schema.lock.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(lock["schema_version"], 2);
    let final_status = run(binary, &config, &schema, &["status"]);
    assert_success(&final_status);
    assert!(String::from_utf8_lossy(&final_status.stdout).contains("Status: synchronized"));

    let transitions = run(
        binary,
        &config,
        &schema,
        &["transitions", "list", "--output", "json"],
    );
    assert_success(&transitions);
    let transitions: serde_json::Value = serde_json::from_slice(&transitions.stdout).unwrap();
    let transition = transitions["transitions"]
        .as_array()
        .unwrap()
        .last()
        .unwrap();
    assert_eq!(transition["state"], "ready");
    let transition_id = transition["transition_id"].as_str().unwrap();

    let waited = run(
        binary,
        &config,
        &schema,
        &["transitions", "wait", transition_id, "--output", "json"],
    );
    assert_success(&waited);
    let waited: serde_json::Value = serde_json::from_slice(&waited.stdout).unwrap();
    assert_eq!(waited["transition_id"], transition_id);
    assert_eq!(waited["state"], "ready");

    let doctor = Command::new(binary)
        .args([
            "doctor",
            "--config",
            &config.display().to_string(),
            "--file",
            &schema.display().to_string(),
            "--output",
            "json",
        ])
        .output()
        .unwrap();
    assert_success(&doctor);
    let doctor: serde_json::Value = serde_json::from_slice(&doctor.stdout).unwrap();
    assert_eq!(doctor["healthy"], true);
}

fn run_generate(binary: &str, schema: &Path, output: &Path) -> Output {
    Command::new(binary)
        .args([
            "generate",
            "--file",
            &schema.display().to_string(),
            "--out",
            &output.display().to_string(),
            "--pkg",
            "workflow",
            "--lang",
            "go",
        ])
        .output()
        .unwrap()
}

fn run(binary: &str, config: &Path, schema: &Path, command: &[&str]) -> Output {
    let mut arguments = vec![
        "schema".to_owned(),
        "--config".to_owned(),
        config.display().to_string(),
        "--file".to_owned(),
        schema.display().to_string(),
    ];
    arguments.extend(command.iter().map(|value| (*value).to_owned()));
    Command::new(binary).args(arguments).output().unwrap()
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "command failed\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn assert_failure(output: &Output) {
    assert!(
        !output.status.success(),
        "command unexpectedly succeeded\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

async fn wait_until_ready(port: u16, child: &mut Child) {
    let client = reqwest::Client::new();
    for _ in 0..100 {
        if let Some(status) = child.try_wait().unwrap() {
            panic!("server exited before readiness: {status}");
        }
        if client
            .get(format!("http://127.0.0.1:{port}/health"))
            .send()
            .await
            .is_ok_and(|response| response.status().is_success())
        {
            return;
        }
        tokio::time::sleep(Duration::from_millis(25)).await;
    }
    panic!("server did not become ready");
}
