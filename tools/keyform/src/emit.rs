fn scalar_tests(codec: &Codec, tests: &mut Tests) {
    let encode = &codec.kernel("encode").expect("validated").path;
    let decode = &codec.kernel("decode").expect("validated").path;
    let name = &codec.name;

    let mut vectors = String::new();
    let _ = writeln!(vectors, "#[test]\nfn {name}_vectors() {{");
    for vector in &codec.vectors {
        match vector {
            Vector::Accept { bytes, value, note } => {
                let literal = bytes_literal(bytes);
                let expr = value_expr(value, "Text");
                if let Some(note) = note {
                    let _ = writeln!(vectors, "    // {}", escape_newlines(note));
                }
                let _ = writeln!(vectors, "    let bytes: &[u8] = {literal};");
                let _ = writeln!(vectors, "    let expected = {expr};");
                let _ = writeln!(
                    vectors,
                    "    let (decoded, consumed) = {decode}(bytes).expect(\"accept vector decodes\");"
                );
                let _ = writeln!(vectors, "    assert_eq!(consumed, bytes.len());");
                if matches!(value, SpecValue::Null) {
                    let _ = writeln!(vectors, "    assert!(decoded.is_null());");
                } else {
                    let _ = writeln!(vectors, "    assert_eq!(decoded, expected);");
                }
                let _ = writeln!(
                    vectors,
                    "    assert_eq!({encode}(&expected).expect(\"accept vector encodes\"), bytes);"
                );
            }
            Vector::Reject { bytes, note } => {
                let literal = bytes_literal(bytes);
                let _ = writeln!(vectors, "    // reject: {}", escape_newlines(note));
                let _ = writeln!(
                    vectors,
                    "    assert!({decode}({literal}).is_err(), {});",
                    rust_string(note)
                );
            }
            Vector::Order { values } => {
                let mut expressions = Vec::new();
                for value in values {
                    let _ = writeln!(
                        vectors,
                        "    let encoded_{} = {encode}(&{}).expect(\"order vector encodes\");",
                        expressions.len(),
                        value_expr(value, "Text")
                    );
                    expressions.push(format!("encoded_{}", expressions.len()));
                }
                for pair in expressions.windows(2) {
                    let _ = writeln!(
                        vectors,
                        "    assert!({} < {}, \"order vector must ascend\");",
                        pair[0], pair[1]
                    );
                }
            }
            Vector::Bound { .. } => panic!("bound vectors belong to scans"),
        }
    }
    vectors.push_str("}\n");
    tests.functions.push(vectors);

    if codec.law("round_trip").is_some() || codec.law("canonical_bytes").is_some() {
        tests.needs_splitmix = true;
        tests.needs_scalar_generator = true;
        tests.needs_values_match = true;
        let mut law = String::new();
        let _ = writeln!(
            law,
            "#[test]\nfn {name}_round_trip_and_canonical_bytes_for_seeded_samples() {{"
        );
        law.push_str("    let mut state = 0x6b65_7966_6f72_6d02_u64;\n");
        law.push_str("    for _ in 0..4096 {\n");
        law.push_str("        let value = generated_scalar(&mut state);\n");
        let _ = writeln!(law, "        let Ok(bytes) = {encode}(&value) else {{");
        law.push_str("            continue;\n        };\n");
        let _ = writeln!(
            law,
            "        let (decoded, consumed) = {decode}(&bytes).expect(\"encoded value decodes\");"
        );
        law.push_str("        assert_eq!(consumed, bytes.len());\n");
        law.push_str(
            "        assert!(values_match(&decoded, &value), \"round trip for {value:?}\");\n",
        );
        let _ = writeln!(
            law,
            "        assert_eq!({encode}(&decoded).expect(\"decoded value re-encodes\"), bytes, \"canonical bytes for {{value:?}}\");"
        );
        law.push_str("    }\n}\n");
        tests.functions.push(law);
    }

    if codec.law("self_delimiting").is_some() {
        tests.needs_splitmix = true;
        tests.needs_scalar_generator = true;
        tests.needs_values_match = true;
        let mut law = String::new();
        let _ = writeln!(law, "#[test]\nfn {name}_is_self_delimiting() {{");
        law.push_str("    let mut state = 0x6b65_7966_6f72_6d03_u64;\n");
        law.push_str("    for _ in 0..2048 {\n");
        law.push_str("        let value = generated_scalar(&mut state);\n");
        let _ = writeln!(law, "        let Ok(bytes) = {encode}(&value) else {{");
        law.push_str("            continue;\n        };\n");
        law.push_str("        let mut extended = bytes.clone();\n");
        law.push_str("        extended.extend_from_slice(&[0xff, 0x00, 0x52, 0x01]);\n");
        let _ = writeln!(
            law,
            "        let (decoded, consumed) = {decode}(&extended).expect(\"prefix still decodes\");"
        );
        law.push_str("        assert_eq!(consumed, bytes.len());\n");
        law.push_str("        assert!(values_match(&decoded, &value));\n");
        law.push_str("    }\n}\n");
        tests.functions.push(law);
    }

    if let Some(law_decl) = codec.law("order_preserving") {
        assert_eq!(
            law_decl.comparator.as_deref(),
            Some("semantic"),
            "scalar-style codecs order by the semantic comparator"
        );
        tests.needs_splitmix = true;
        tests.needs_scalar_generator = true;
        let mut law = String::new();
        let _ = writeln!(
            law,
            "#[test]\nfn {name}_order_matches_semantic_comparison() {{"
        );
        law.push_str("    let mut state = 0x6b65_7966_6f72_6d04_u64;\n");
        law.push_str("    for _ in 0..4096 {\n");
        law.push_str("        let left = generated_scalar(&mut state);\n");
        law.push_str("        let right = generated_scalar(&mut state);\n");
        law.push_str("        let Ok(expected) = left.compare(&right) else {\n");
        law.push_str("            continue;\n        };\n");
        let _ = writeln!(
            law,
            "        let (Ok(left_bytes), Ok(right_bytes)) = ({encode}(&left), {encode}(&right)) else {{"
        );
        law.push_str("            continue;\n        };\n");
        law.push_str("        assert_eq!(\n");
        law.push_str("            left_bytes.cmp(&right_bytes),\n");
        law.push_str("            expected,\n");
        law.push_str("            \"key order disagrees for {left:?} and {right:?}\"\n");
        law.push_str("        );\n");
        law.push_str("    }\n}\n");
        tests.functions.push(law);
    }
}

