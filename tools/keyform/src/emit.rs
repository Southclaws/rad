fn kv_encode_helper(spec: &Spec) -> String {
    let codec = spec
        .codecs
        .iter()
        .find(|codec| {
            matches!(style(codec), Style::TaggedCases) && codec.kernel("module").is_some()
        })
        .expect("validator requires a tagged-case codec for kv_encode");
    let module = &codec.kernel("module").expect("checked above").path;
    let mut out = String::new();
    out.push_str(
        "/// Key encoding for one scalar, `None` for values the ordered key\n/// layer cannot represent.\n",
    );
    out.push_str("fn kv_encode(value: &Value) -> Option<Vec<u8>> {\n");
    out.push_str("    Some(match value {\n");
    for case in &codec.cases {
        let encoder = case
            .encoder
            .as_ref()
            .expect("validator requires encoders on tagged cases");
        let call = format!("{module}::{}", encoder.name);
        let arm = match case.name.as_str() {
            "null" => format!("Value::Null(_) => {call}().to_vec(),"),
            "bool" => format!("Value::Bool(value) => {call}(*value).to_vec(),"),
            "int64" => format!("Value::Int64(value) => {call}(*value).to_vec(),"),
            "float64" => match encoder.form {
                EncoderForm::OptionArray => {
                    format!("Value::Float64(value) => {call}(*value)?.to_vec(),")
                }
                _ => format!("Value::Float64(value) => {call}(*value).to_vec(),"),
            },
            "text" => format!("Value::Text(value) => {call}(value),"),
            "bytes" => format!("Value::Bytes(value) => {call}(value.as_slice()),"),
            other => panic!("unknown tagged case {other:?}"),
        };
        let _ = writeln!(out, "        {arm}");
    }
    out.push_str("    })\n}\n\n");
    out
}

