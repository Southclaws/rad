/// Rust parameter list for a space's encode function, in field order.
fn key_parameters(space: &Space) -> Vec<(String, &'static str)> {
    space
        .fields
        .iter()
        .map(|field| {
            let rust_type = match &field.kind {
                SegmentKind::PhysicalId(_) | SegmentKind::Uvarint | SegmentKind::Be64 => "u64",
                SegmentKind::Be32 => "u32",
                SegmentKind::Tuple | SegmentKind::LenBytes | SegmentKind::Bytes => "&[u8]",
                SegmentKind::Text => "&str",
            };
            (field.name.clone(), rust_type)
        })
        .collect()
}

/// Index of the first field in the terminal run (tuples and raw tails);
/// prefix functions exist for every boundary before it.
fn terminal_run_start(space: &Space) -> usize {
    space
        .fields
        .iter()
        .position(|field| {
            matches!(
                field.kind,
                SegmentKind::Tuple | SegmentKind::Text | SegmentKind::Bytes
            )
        })
        .unwrap_or(space.fields.len())
}

fn parts_struct_name(space: &Space) -> String {
    let mut name = String::new();
    for part in space.name.split('_') {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            name.push(first.to_ascii_uppercase());
            name.push_str(chars.as_str());
        }
    }
    name.push_str("KeyParts");
    name
}

/// Decoded fields exposed by a space's parts struct. Consecutive trailing
/// tuple fields merge into one raw `tuple_rest` blob because scalar tuples
/// carry no arity of their own.
fn parts_fields(space: &Space) -> Vec<(String, &'static str)> {
    let mut fields = Vec::new();
    let tuple_count = space
        .fields
        .iter()
        .filter(|field| matches!(field.kind, SegmentKind::Tuple))
        .count();
    let mut tuple_emitted = false;
    for field in &space.fields {
        let entry = match &field.kind {
            SegmentKind::PhysicalId(_) | SegmentKind::Uvarint | SegmentKind::Be64 => {
                (field.name.clone(), "u64")
            }
            SegmentKind::Be32 => (field.name.clone(), "u32"),
            SegmentKind::LenBytes | SegmentKind::Bytes => (field.name.clone(), "Vec<u8>"),
            SegmentKind::Text => (field.name.clone(), "String"),
            SegmentKind::Tuple => {
                if tuple_count > 1 {
                    if tuple_emitted {
                        continue;
                    }
                    tuple_emitted = true;
                    ("tuple_rest".to_owned(), "Vec<u8>")
                } else {
                    (field.name.clone(), "Vec<u8>")
                }
            }
        };
        fields.push(entry);
    }
    fields
}

fn key_vector_tests(keyspace: &Keyspace, space: &Space) -> String {
    let name = &space.name;
    let mut out = String::new();
    let _ = writeln!(out, "#[test]\nfn {name}_key_vectors() {{");
    let parameters = key_parameters(space);
    let multi_tuple = space
        .fields
        .iter()
        .filter(|field| matches!(field.kind, SegmentKind::Tuple))
        .count()
        > 1;
    for vector in &space.vectors {
        if let Some(note) = &vector.note {
            let _ = writeln!(out, "    // {}", escape_newlines(note));
        }
        let mut arguments = Vec::new();
        let mut tuple_rest = Vec::new();
        let mut decode_asserts = Vec::new();
        for (field, (parameter, _)) in space.fields.iter().zip(&parameters) {
            let value = vector
                .fields
                .iter()
                .find(|(name, _)| name == parameter)
                .map(|(_, value)| value)
                .unwrap_or_else(|| panic!("vector for {name} lacks field {parameter}"));
            match (&field.kind, value) {
                (
                    SegmentKind::PhysicalId(_)
                    | SegmentKind::Uvarint
                    | SegmentKind::Be32
                    | SegmentKind::Be64,
                    KeyFieldValue::Number(number),
                ) => {
                    arguments.push(number.to_string());
                    decode_asserts.push(format!("    assert_eq!(parts.{parameter}, {number});"));
                }
                (
                    SegmentKind::Tuple | SegmentKind::LenBytes | SegmentKind::Bytes,
                    KeyFieldValue::Bytes(bytes),
                ) => {
                    arguments.push(bytes_literal(bytes));
                    if matches!(field.kind, SegmentKind::Tuple) && multi_tuple {
                        tuple_rest.extend_from_slice(bytes);
                    } else {
                        decode_asserts.push(format!(
                            "    assert_eq!(parts.{parameter}, {});",
                            byte_vec_expr(bytes)
                        ));
                    }
                }
                (SegmentKind::Text, KeyFieldValue::Text(text)) => {
                    arguments.push(rust_string(text));
                    decode_asserts.push(format!(
                        "    assert_eq!(parts.{parameter}, {});",
                        rust_string(text)
                    ));
                }
                (kind, value) => panic!(
                    "vector field {parameter} for {name} has kind {kind:?} but value {value:?}"
                ),
            }
        }
        if multi_tuple {
            decode_asserts.push(format!(
                "    assert_eq!(parts.tuple_rest, {});",
                byte_vec_expr(&tuple_rest)
            ));
        }
        let _ = writeln!(
            out,
            "    let key = rad::engine::kv::keys::{name}_key({});",
            arguments.join(", ")
        );
        let _ = writeln!(
            out,
            "    assert_eq!(key, {});",
            bytes_literal(&vector.bytes)
        );
        if !space.fields.is_empty() {
            let _ = writeln!(
                out,
                "    let parts = rad::engine::kv::keys::decode_{name}_key(&key).expect(\"vector decodes\");"
            );
            for assert in decode_asserts {
                let _ = writeln!(out, "{assert}");
            }
        }
        let _ = writeln!(
            out,
            "    assert!(rad::engine::exec::key_describe::describe_key(&key).is_some());"
        );
    }
    let _ = keyspace;
    out.push_str("}\n");
    out
}

fn scan_tests(scan: &Scan, tests: &mut Tests) {
    let kernel = &scan.kernel;
    tests.needs_splitmix = true;
    let mut out = String::new();
    out.push_str("#[test]\nfn prefix_scan_bounds_are_smallest_and_exclusive() {\n");
    for bound in &scan.bounds {
        let Vector::Bound { prefix, end } = bound else {
            panic!("scan blocks carry bound vectors only");
        };
        match end {
            Some(end) => {
                let _ = writeln!(
                    out,
                    "    assert_eq!({kernel}({}), Some(vec!{}));",
                    bytes_literal(prefix),
                    bytes_literal(end).trim_start_matches('&')
                );
            }
            None => {
                let _ = writeln!(
                    out,
                    "    assert_eq!({kernel}({}), None);",
                    bytes_literal(prefix)
                );
            }
        }
    }
    out.push_str("    let mut state = 0x6b65_7966_6f72_6d0a_u64;\n");
    out.push_str("    for _ in 0..2048 {\n");
    out.push_str("        let length = 1 + (splitmix64(&mut state) % 6) as usize;\n");
    out.push_str("        let prefix: Vec<u8> = (0..length).map(|_| splitmix64(&mut state) as u8).collect();\n");
    let _ = writeln!(out, "        match {kernel}(&prefix) {{");
    out.push_str("            Some(end) => {\n");
    out.push_str("                assert!(prefix < end);\n");
    out.push_str("                assert!(end.len() <= prefix.len());\n");
    out.push_str(
        "                for suffix in [&[][..], &[0x00][..], &[0xff][..], &[0xff, 0xff][..]] {\n",
    );
    out.push_str("                    let mut key = prefix.clone();\n");
    out.push_str("                    key.extend_from_slice(suffix);\n");
    out.push_str(
        "                    assert!(key < end, \"suffixed key must stay under the bound\");\n",
    );
    out.push_str("                }\n");
    out.push_str("            }\n");
    out.push_str("            None => assert!(prefix.iter().all(|byte| *byte == 0xff)),\n");
    out.push_str("        }\n");
    out.push_str("    }\n}\n");
    tests.functions.push(out);
}
