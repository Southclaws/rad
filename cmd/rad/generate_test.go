const acceptedSchemaFixture = `
tables:
  - id: 1
    name: users
    columns:
      - { id: 1, name: id, type: string, pk: true }
`

func TestGenerateOneUsesAcceptedIdentity(t *testing.T) {
	directory := t.TempDir()
	desired := filepath.Join(directory, config.DefaultSchemaFile)
	if err := os.WriteFile(desired, []byte(acceptedSchemaFixture), 0o600); err != nil {
		t.Fatal(err)
	}
	accepted := acceptedFixture(t, 4)
	if err := generateOne(&cobra.Command{}, desired, filepath.Join(directory, "generated"), "db", "go", accepted); err != nil {
		t.Fatal(err)
	}
	generated, err := os.ReadFile(filepath.Join(directory, "generated", codegen.GoClientFilename))
	if err != nil {
		t.Fatal(err)
	}
	for _, expected := range []string{"SchemaVersion uint64 = 4", accepted.Lock.SchemaHash, "const RawSchema"} {
		if !strings.Contains(string(generated), expected) {
			t.Errorf("generated client missing %q", expected)
		}
	}
}

func TestGenerateOneRemovesOnlySupersededRadGoClients(t *testing.T) {
	directory := t.TempDir()
	desired := filepath.Join(directory, config.DefaultSchemaFile)
	if err := os.WriteFile(desired, []byte(acceptedSchemaFixture), 0o600); err != nil {
		t.Fatal(err)
	}
	output := filepath.Join(directory, "generated")
	if err := os.MkdirAll(output, 0o755); err != nil {
		t.Fatal(err)
	}
	old := filepath.Join(output, "db.go")
	if err := os.WriteFile(old, []byte("// Code generated by rad generate. DO NOT EDIT.\npackage db\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	handwritten := filepath.Join(output, "helpers.go")
	if err := os.WriteFile(handwritten, []byte("package db\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := generateOne(&cobra.Command{}, desired, output, "db", "go", acceptedFixture(t, 4)); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(old); !os.IsNotExist(err) {
		t.Fatalf("superseded generated file still exists: %v", err)
	}
	if _, err := os.Stat(handwritten); err != nil {
		t.Fatalf("handwritten Go file was removed: %v", err)
	}
}

