func TestGenerateOneRefusesUnappliedDesiredSchema(t *testing.T) {
	directory := t.TempDir()
	desired := filepath.Join(directory, config.DefaultSchemaFile)
	modified := strings.Replace(acceptedSchemaFixture, "users", "accounts", 1)
	if err := os.WriteFile(desired, []byte(modified), 0o600); err != nil {
		t.Fatal(err)
	}
	err := generateOne(&cobra.Command{}, desired, filepath.Join(directory, "generated"), "db", "go", acceptedFixture(t, 4))
	if err == nil || !strings.Contains(err.Error(), "rad schema migrate") {
		t.Fatalf("error = %v", err)
	}
}

func acceptedFixture(t *testing.T, version uint64) projectstate.Accepted {
	t.Helper()
	parsed, err := catalogschema.Parse("accepted.rad.schema.yaml", []byte(acceptedSchemaFixture))
	if err != nil {
		t.Fatal(err)
	}
	canonical := parsed.Canonical()
	hash, err := canonical.Hash()
	if err != nil {
		t.Fatal(err)
	}
	return projectstate.Accepted{
		Lock:   projectstate.Lock{FormatVersion: projectstate.FormatVersion, SchemaVersion: version, SchemaHash: hash},
		Source: []byte(acceptedSchemaFixture), Schema: canonical,
	}
}
