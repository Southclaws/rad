package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"

	"github.com/Southclaws/rad/rad/codegen"
	_ "github.com/Southclaws/rad/rad/codegen/golang"
	_ "github.com/Southclaws/rad/rad/codegen/typescript"
	"github.com/Southclaws/rad/rad/engine/02_catalog/schema"
	projectstate "github.com/Southclaws/rad/rad/state"
)

func generateCmd() *cobra.Command {
	var file, out, pkg, lang string
	cmd := &cobra.Command{
		Use:   "generate",
		Short: "Generate a typed client for the accepted schema",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			absoluteFile, err := filepath.Abs(file)
			if err != nil {
				return err
			}
			accepted, err := projectstate.New(filepath.Join(filepath.Dir(absoluteFile), defaultStateDir)).Load()
			if err != nil {
				return fmt.Errorf("load accepted schema state: %w", err)
			}
			return generateOne(cmd, absoluteFile, out, pkg, lang, accepted)
		},
	}
	cmd.Flags().StringVarP(&file, "file", "f", defaultSchemaFile, "desired schema file")
	cmd.Flags().StringVarP(&out, "out", "o", "generated", "output directory")
	cmd.Flags().StringVar(&pkg, "pkg", "db", "generated package or client name")
	cmd.Flags().StringVar(&lang, "lang", "go", "client language: go, ts")
	return cmd
}

func generateProject(cmd *cobra.Command, project project, accepted projectstate.Accepted) error {
	for _, target := range project.Config.Generate {
		output := target.Output
		if !filepath.IsAbs(output) {
			output = filepath.Join(project.Root, output)
		}
		if err := generateOne(cmd, project.SchemaFile, output, target.Package, target.Language, accepted); err != nil {
			return err
		}
	}
	return nil
}

func generateOne(
	cmd *cobra.Command,
	desiredFile, output, pkg, language string,
	accepted projectstate.Accepted,
) error {
	desired, err := os.ReadFile(desiredFile)
	if err != nil {
		return err
	}
	matches, _, err := projectstate.MatchesAccepted(desiredFile, desired, accepted)
	if err != nil {
		return err
	}
	if !matches {
		return fmt.Errorf(
			"%s differs from accepted schema version %d\n\nApply it with:\n  rad schema migrate\n\nOr restore the accepted schema with:\n  rad schema pull",
			desiredFile, accepted.Lock.SchemaVersion)
	}
	parsed, err := schema.Parse(desiredFile, accepted.Source)
	if err != nil {
		return err
	}
	name := language
	if name == "typescript" {
		name = "ts"
	}
	generator, ok := codegen.Lookup(name)
	if !ok {
		return fmt.Errorf("unknown language %q (have: %v)", language, codegen.Languages())
	}
	model, err := codegen.Build(pkg, parsed)
	if err != nil {
		return err
	}
	files, err := generator.Generate(model, codegen.Options{
		Package: pkg, SchemaSource: accepted.Source,
		SchemaVersion: accepted.Lock.SchemaVersion, SchemaHash: accepted.Lock.SchemaHash,
	})
	if err != nil {
		return err
	}
	extension := map[string]string{"go": ".go", "ts": ".ts"}[name]
	if extension != "" {
		if err := removeSupersededGeneratedClients(output, files, extension); err != nil {
			return err
		}
	}
	for _, file := range files {
		destination := filepath.Join(output, file.Path)
		if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(destination, file.Content, 0o644); err != nil {
			return err
		}
		fmt.Fprintf(cmd.OutOrStdout(), "%s: generated %s (%d tables) for schema v%d\n",
			desiredFile, destination, len(parsed.Tables), accepted.Lock.SchemaVersion)
	}
	return nil
}

func removeSupersededGeneratedClients(output string, files []codegen.GeneratedFile, extension string) error {
	keep := make(map[string]bool, len(files))
	for _, file := range files {
		keep[filepath.Clean(file.Path)] = true
	}
	entries, err := os.ReadDir(output)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	const generatedHeader = "// Code generated by rad generate. DO NOT EDIT."
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != extension || keep[entry.Name()] {
			continue
		}
		path := filepath.Join(output, entry.Name())
		source, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if strings.HasPrefix(string(source), generatedHeader) {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}
