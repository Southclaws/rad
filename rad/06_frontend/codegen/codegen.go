package codegen

import (
	"bytes"
	"fmt"
	"go/format"

	"rad/rad/02_catalog/schema"
)

// Generate emits the typed Go client for a schema as a single gofmt-ed
// source file declaring package pkg. schemaSrc is embedded verbatim so the
// client can migrate its own database.
func Generate(pkg string, sch *schema.Schema, schemaSrc []byte) ([]byte, error) {
	m, err := build(pkg, sch)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	emitHeader(p, m, schemaSrc)
	for _, t := range m.Tables {
		emitModel(p, t)
		emitCreateAndPatch(p, t)
		emitTableHandle(p, t)
		emitQuery(p, t)
		emitInclude(p, t)
		emitConverters(p, t)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("codegen: generated source does not format (bug): %w\n%s", err, b.Bytes())
	}
	return src, nil
}

func emitHeader(p func(string, ...any), m *genModel, schemaSrc []byte) {
	p("// Code generated by rad generate. DO NOT EDIT.")
	p("//")
	p("// Typed client for the RAD database described by schema.rad. All access")
	p("// goes through the RAD frontend — no SQL anywhere.")
	p("package %s", m.Pkg)
	p("")
	p("import (")
	p("\t\"context\"")
	p("\t\"path/filepath\"")
	p("")
	p("\tkv \"rad/rad/01_kv\"")
	p("\t\"rad/rad/01_kv/kvmem\"")
	p("\t\"rad/rad/01_kv/kvslate\"")
	p("\tlir \"rad/rad/03_lir\"")
	p("\tfrontend \"rad/rad/06_frontend\"")
	p(")")
	p("")
	p("// SchemaSource is the schema.rad this client was generated from.")
	p("const SchemaSource = %q", string(schemaSrc))
	p("")

	// Client and Tx expose one handle per table.
	p("// Client is the database handle. Open (file-backed), OpenMemory (tests),")
	p("// or New (bring your own store) — then use the table handles.")
	p("type Client struct {")
	p("\tdb *frontend.DB")
	p("\tcloser interface{ Close() error }")
	for _, t := range m.Tables {
		p("\t%s %sTable", goName(t.SQLName), t.Model)
	}
	p("}")
	p("")
	p("func New(db *frontend.DB) *Client {")
	p("\tc := &Client{db: db}")
	for _, t := range m.Tables {
		p("\tc.%s = %sTable{v: db}", goName(t.SQLName), t.Model)
	}
	p("\treturn c")
	p("}")
	p("")
	p("// Open opens (creating if needed) a file-backed database at dir.")
	p("func Open(dir string) (*Client, error) {")
	p("\tabs, err := filepath.Abs(dir)")
	p("\tif err != nil {")
	p("\t\treturn nil, err")
	p("\t}")
	p("\tstore, err := kvslate.Open(abs, \"file://\")")
	p("\tif err != nil {")
	p("\t\treturn nil, err")
	p("\t}")
	p("\tc := New(frontend.Open(store, \"public\"))")
	p("\tc.closer = store")
	p("\treturn c, nil")
	p("}")
	p("")
	p("// OpenMemory opens an in-memory database — handy for application tests.")
	p("func OpenMemory() *Client {")
	p("\treturn New(frontend.Open(kvmem.New(), \"public\"))")
	p("}")
	p("")
	p("func (c *Client) Close() error {")
	p("\tif c.closer != nil {")
	p("\t\treturn c.closer.Close()")
	p("\t}")
	p("\treturn nil")
	p("}")
	p("")
	p("// Migrate reconciles the database with SchemaSource and returns the")
	p("// applied steps.")
	p("func (c *Client) Migrate(ctx context.Context) ([]string, error) {")
	p("\tsteps, err := c.db.MigrateFile(ctx, \"schema.rad\", []byte(SchemaSource))")
	p("\tif err != nil {")
	p("\t\treturn nil, err")
	p("\t}")
	p("\tout := make([]string, len(steps))")
	p("\tfor i, s := range steps {")
	p("\t\tout[i] = s.String()")
	p("\t}")
	p("\treturn out, nil")
	p("}")
	p("")
	p("// Tx runs fn in a serializable transaction; retry on IsConflict.")
	p("func (c *Client) Tx(ctx context.Context, fn func(tx *Tx) error) error {")
	p("\treturn c.db.Txn(ctx, func(ftx *frontend.Tx) error {")
	p("\t\ttx := &Tx{}")
	for _, t := range m.Tables {
		p("\t\ttx.%s = %sTable{v: ftx}", goName(t.SQLName), t.Model)
	}
	p("\t\treturn fn(tx)")
	p("\t})")
	p("}")
	p("")
	p("// IsConflict reports whether err is a transaction conflict worth retrying.")
	p("func IsConflict(err error) bool { return frontend.IsConflict(err) }")
	p("")
	p("// Tx mirrors the Client's table handles inside a transaction.")
	p("type Tx struct {")
	for _, t := range m.Tables {
		p("\t%s %sTable", goName(t.SQLName), t.Model)
	}
	p("}")
	p("")
	p("// view is the frontend surface both *frontend.DB and *frontend.Tx provide.")
	p("type view interface {")
	p("\tCreate(ctx context.Context, table string, row lir.Row) (lir.Row, error)")
	p("\tUpdate(ctx context.Context, table string, key, set lir.Row) (lir.Row, bool, error)")
	p("\tDelete(ctx context.Context, table string, key lir.Row) (bool, error)")
	p("\tGet(ctx context.Context, table string, key lir.Row) (lir.Row, bool, error)")
	p("\tRead(ctx context.Context, r lir.Read) ([]*frontend.Record, error)")
	p("}")
	p("")
	p("var (")
	p("\t_ view = (*frontend.DB)(nil)")
	p("\t_ view = (*frontend.Tx)(nil)")
	p(")")
	p("")
	// Shared nullable decode helpers.
	for _, bt := range []struct{ name, typ, field string }{
		{"stringPtr", "string", "Text"},
		{"int64Ptr", "int64", "Int64"},
		{"float64Ptr", "float64", "Float64"},
		{"boolPtr", "bool", "Bool"},
	} {
		p("func %s(v lir.Value) *%s {", bt.name, bt.typ)
		p("\tif v.Null {")
		p("\t\treturn nil")
		p("\t}")
		p("\tx := v.%s", bt.field)
		p("\treturn &x")
		p("}")
		p("")
	}
	p("// ensure imports are used even for degenerate schemas")
	p("var _ kv.KV = (*kvmem.Store)(nil)")
	p("")
}

// emitModel writes the row struct: columns, then forward relation pointers,
// then reverse relation slices (populated only when included).
func emitModel(p func(string, ...any), t *genTable) {
	p("// %s is one row of %q. Relation fields are populated only when the", t.Model, t.SQLName)
	p("// corresponding Include* option was used on the query.")
	p("type %s struct {", t.Model)
	for _, c := range t.Cols {
		typ := c.GoType
		if c.Nullable {
			typ = "*" + c.GoType
		}
		p("\t%s %s `json:%q`", c.Field, typ, c.SQLName+jsonOmit(c.Nullable))
	}
	for _, r := range t.Forward {
		p("\t%s *%s `json:%q`", r.Field, r.Target.Model, r.As+",omitempty")
	}
	for _, r := range t.Reverse {
		p("\t%s []%s `json:%q`", r.Field, r.Target.Model, r.As+",omitempty")
	}
	p("}")
	p("")
}

func jsonOmit(nullable bool) string {
	if nullable {
		return ",omitempty"
	}
	return ""
}

// emitCreateAndPatch writes the input structs: required fields are bare,
// optional (nullable or defaulted) fields are pointers.
func emitCreateAndPatch(p func(string, ...any), t *genTable) {
	p("// %sCreate is the input to Create. Pointer fields are optional:", t.Model)
	p("// nil defers to the column default or NULL.")
	p("type %sCreate struct {", t.Model)
	for _, c := range t.Cols {
		if c.Nullable || c.HasDef {
			p("\t%s *%s", c.Field, c.GoType)
		} else {
			p("\t%s %s", c.Field, c.GoType)
		}
	}
	p("}")
	p("")
	p("// %sPatch is the input to Update. Nil fields are left untouched;", t.Model)
	p("// Clear* sets a nullable column to NULL.")
	p("type %sPatch struct {", t.Model)
	for _, c := range t.Cols {
		if c.IsPK {
			continue
		}
		p("\t%s *%s", c.Field, c.GoType)
	}
	for _, c := range t.Cols {
		if c.IsPK || !c.Nullable {
			continue
		}
		p("\tClear%s bool", c.Field)
	}
	p("}")
	p("")
}

// pkParams renders the primary key as Go parameters, e.g.
// "teamID string, userID string".
func pkParams(t *genTable) string {
	out := ""
	for i, c := range t.PK {
		if i > 0 {
			out += ", "
		}
		out += lowerFirst(c.Field) + " " + c.GoType
	}
	return out
}

func pkKeyRow(t *genTable) string {
	out := "lir.Row{"
	for i, c := range t.PK {
		if i > 0 {
			out += ", "
		}
		out += fmt.Sprintf("%q: %s(%s)", c.SQLName, lirCtor(c.Type), lowerFirst(c.Field))
	}
	return out + "}"
}

func lowerFirst(s string) string {
	if s == "ID" {
		return "id"
	}
	out := []byte(s)
	i := 0
	for i < len(out) && out[i] >= 'A' && out[i] <= 'Z' {
		// consume leading initialism carefully: only lowercase the first
		// rune unless the next is lowercase (BoardID -> boardID)
		break
	}
	out[0] = out[0] - 'A' + 'a'
	_ = i
	return string(out)
}

// emitTableHandle writes CRUD + unique lookups.
func emitTableHandle(p func(string, ...any), t *genTable) {
	h := t.Model + "Table"
	p("// %s provides typed access to %q.", h, t.SQLName)
	p("type %s struct{ v view }", h)
	p("")

	// Create.
	p("func (t %s) Create(ctx context.Context, in %sCreate) (%s, error) {", h, t.Model, t.Model)
	p("\trow := lir.Row{}")
	for _, c := range t.Cols {
		if c.Nullable || c.HasDef {
			p("\tif in.%s != nil {", c.Field)
			p("\t\trow[%q] = %s(*in.%s)", c.SQLName, lirCtor(c.Type), c.Field)
			p("\t}")
		} else {
			p("\trow[%q] = %s(in.%s)", c.SQLName, lirCtor(c.Type), c.Field)
		}
	}
	p("\tstored, err := t.v.Create(ctx, %q, row)", t.SQLName)
	p("\tif err != nil {")
	p("\t\treturn %s{}, err", t.Model)
	p("\t}")
	p("\treturn %sFromRow(stored), nil", lowerFirst(t.Model))
	p("}")
	p("")

	// Get by primary key.
	p("func (t %s) Get(ctx context.Context, %s) (%s, bool, error) {", h, pkParams(t), t.Model)
	p("\trow, ok, err := t.v.Get(ctx, %q, %s)", t.SQLName, pkKeyRow(t))
	p("\tif err != nil || !ok {")
	p("\t\treturn %s{}, false, err", t.Model)
	p("\t}")
	p("\treturn %sFromRow(row), true, nil", lowerFirst(t.Model))
	p("}")
	p("")

	// Update by primary key.
	p("func (t %s) Update(ctx context.Context, %s, patch %sPatch) (%s, bool, error) {", h, pkParams(t), t.Model, t.Model)
	p("\tset := lir.Row{}")
	for _, c := range t.Cols {
		if c.IsPK {
			continue
		}
		p("\tif patch.%s != nil {", c.Field)
		p("\t\tset[%q] = %s(*patch.%s)", c.SQLName, lirCtor(c.Type), c.Field)
		p("\t}")
		if c.Nullable {
			p("\tif patch.Clear%s {", c.Field)
			p("\t\tset[%q] = lir.Null(%q)", c.SQLName, string(c.Type))
			p("\t}")
		}
	}
	p("\trow, ok, err := t.v.Update(ctx, %q, %s, set)", t.SQLName, pkKeyRow(t))
	p("\tif err != nil || !ok {")
	p("\t\treturn %s{}, false, err", t.Model)
	p("\t}")
	p("\treturn %sFromRow(row), true, nil", lowerFirst(t.Model))
	p("}")
	p("")

	// Delete by primary key.
	p("func (t %s) Delete(ctx context.Context, %s) (bool, error) {", h, pkParams(t))
	p("\treturn t.v.Delete(ctx, %q, %s)", t.SQLName, pkKeyRow(t))
	p("}")
	p("")

	// Unique lookups.
	for _, uq := range t.Uniques {
		name := "By"
		params := ""
		for i, c := range uq {
			name += c.Field
			if i > 0 {
				params += ", "
			}
			params += lowerFirst(c.Field) + " " + c.GoType
		}
		p("// %s finds the row by the unique index on (%s).", name, uqCols(uq))
		p("func (t %s) %s(ctx context.Context, %s) (%s, bool, error) {", h, name, params, t.Model)
		p("\trecs, err := t.v.Read(ctx, lir.Read{Table: %q, Filter: lir.And{Exprs: []lir.Expr{", t.SQLName)
		for _, c := range uq {
			p("\t\tlir.Eq{Left: lir.ColRef{Column: %q}, Right: lir.Literal{Value: %s(%s)}},", c.SQLName, lirCtor(c.Type), lowerFirst(c.Field))
		}
		p("\t}}, Limit: 1})")
		p("\tif err != nil || len(recs) == 0 {")
		p("\t\treturn %s{}, false, err", t.Model)
		p("\t}")
		p("\treturn %sFromRecord(recs[0]), true, nil", lowerFirst(t.Model))
		p("}")
		p("")
	}

	// Query entry point.
	p("func (t %s) Query() *%sQuery {", h, t.Model)
	p("\treturn &%sQuery{v: t.v, read: lir.Read{Table: %q}}", t.Model, t.SQLName)
	p("}")
	p("")
}

func uqCols(uq []genCol) string {
	out := ""
	for i, c := range uq {
		if i > 0 {
			out += ", "
		}
		out += c.SQLName
	}
	return out
}

// emitQuery writes the fluent query builder.
func emitQuery(p func(string, ...any), t *genTable) {
	q := t.Model + "Query"
	p("// %s is a fluent shaped-read builder for %q. Conditions AND together.", q, t.SQLName)
	p("type %s struct {", q)
	p("\tv view")
	p("\tread lir.Read")
	p("\tfilters []lir.Expr")
	p("}")
	p("")

	emitFilterMethods(p, t, q, "q", "q.filters = append(q.filters, %s)")
	emitOrderMethods(p, t, q)

	p("func (q *%s) Limit(n int) *%s { q.read.Limit = n; return q }", q, q)
	p("func (q *%s) Offset(n int) *%s { q.read.Offset = n; return q }", q, q)
	p("")

	emitIncludeMethods(p, t, q, "q.read.Include = append(q.read.Include, inc)")

	p("// All executes the query.")
	p("func (q *%s) All(ctx context.Context) ([]%s, error) {", q, t.Model)
	p("\tif len(q.filters) == 1 {")
	p("\t\tq.read.Filter = q.filters[0]")
	p("\t} else if len(q.filters) > 1 {")
	p("\t\tq.read.Filter = lir.And{Exprs: q.filters}")
	p("\t}")
	p("\trecs, err := q.v.Read(ctx, q.read)")
	p("\tif err != nil {")
	p("\t\treturn nil, err")
	p("\t}")
	p("\tout := make([]%s, len(recs))", t.Model)
	p("\tfor i, r := range recs {")
	p("\t\tout[i] = %sFromRecord(r)", lowerFirst(t.Model))
	p("\t}")
	p("\treturn out, nil")
	p("}")
	p("")
	p("// First executes the query with limit 1.")
	p("func (q *%s) First(ctx context.Context) (%s, bool, error) {", q, t.Model)
	p("\tq.read.Limit = 1")
	p("\trows, err := q.All(ctx)")
	p("\tif err != nil || len(rows) == 0 {")
	p("\t\treturn %s{}, false, err", t.Model)
	p("\t}")
	p("\treturn rows[0], true, nil")
	p("}")
	p("")
}

// emitFilterMethods writes typed column predicates onto builder type q with
// receiver recv; appendStmt is a printf pattern receiving the expression.
func emitFilterMethods(p func(string, ...any), t *genTable, q, recv, appendStmt string) {
	add := func(sig, expr string) {
		p("func (%s *%s) %s *%s {", recv, q, sig, q)
		p("\t"+appendStmt, expr)
		p("\treturn %s", recv)
		p("}")
	}
	for _, c := range t.Cols {
		colRef := fmt.Sprintf("lir.ColRef{Column: %q}", c.SQLName)
		lit := fmt.Sprintf("lir.Literal{Value: %s(v)}", lirCtor(c.Type))
		add(fmt.Sprintf("%sEq(v %s)", c.Field, c.GoType),
			fmt.Sprintf("lir.Eq{Left: %s, Right: %s}", colRef, lit))
		add(fmt.Sprintf("%sNe(v %s)", c.Field, c.GoType),
			fmt.Sprintf("lir.Cmp{Op: lir.OpNe, Left: %s, Right: %s}", colRef, lit))
		if c.Type != "bool" {
			for _, op := range []struct{ name, op string }{
				{"Lt", "OpLt"}, {"Lte", "OpLte"}, {"Gt", "OpGt"}, {"Gte", "OpGte"},
			} {
				add(fmt.Sprintf("%s%s(v %s)", c.Field, op.name, c.GoType),
					fmt.Sprintf("lir.Cmp{Op: lir.%s, Left: %s, Right: %s}", op.op, colRef, lit))
			}
		}
		if c.Nullable {
			add(fmt.Sprintf("%sNull()", c.Field),
				fmt.Sprintf("lir.IsNull{Expr: %s}", colRef))
			add(fmt.Sprintf("%sNotNull()", c.Field),
				fmt.Sprintf("lir.Not{Expr: lir.IsNull{Expr: %s}}", colRef))
		}
	}
	p("")
}

func emitOrderMethods(p func(string, ...any), t *genTable, q string) {
	for _, c := range t.Cols {
		p("func (q *%s) OrderBy%s() *%s {", q, c.Field, q)
		p("\tq.read.OrderBy = append(q.read.OrderBy, lir.OrderTerm{Column: %q})", c.SQLName)
		p("\treturn q")
		p("}")
		p("func (q *%s) OrderBy%sDesc() *%s {", q, c.Field, q)
		p("\tq.read.OrderBy = append(q.read.OrderBy, lir.OrderTerm{Column: %q, Desc: true})", c.SQLName)
		p("\treturn q")
		p("}")
	}
	p("")
}

// emitIncludeMethods writes Include* methods for both relation directions.
func emitIncludeMethods(p func(string, ...any), t *genTable, q, appendStmt string) {
	for _, r := range t.Forward {
		p("// Include%s embeds the referenced %s (nil when the FK is NULL).", r.Field, r.Target.Model)
		p("func (q *%s) Include%s(opts ...func(*%sInclude)) *%s {", q, r.Field, r.Target.Model, q)
		p("\tb := &%sInclude{inc: lir.Include{FK: %q, Dir: lir.ToParent, As: %q}}", r.Target.Model, r.FKName, r.As)
		p("\tfor _, o := range opts {")
		p("\t\to(b)")
		p("\t}")
		p("\tinc := b.inc")
		p("\t" + appendStmt)
		p("\treturn q")
		p("}")
	}
	for _, r := range t.Reverse {
		p("// Include%s embeds the %s rows referencing this row.", r.Field, r.Target.Model)
		p("func (q *%s) Include%s(opts ...func(*%sInclude)) *%s {", q, r.Field, r.Target.Model, q)
		p("\tb := &%sInclude{inc: lir.Include{FK: %q, Dir: lir.ToChildren, As: %q}}", r.Target.Model, r.FKName, r.As)
		p("\tfor _, o := range opts {")
		p("\t\to(b)")
		p("\t}")
		p("\tb.inc.Filter = b.filter()")
		p("\tinc := b.inc")
		p("\t" + appendStmt)
		p("\treturn q")
		p("}")
	}
	p("")
}

// emitInclude writes the include builder used to refine child fetches
// (filter, order, limit, nested includes).
func emitInclude(p func(string, ...any), t *genTable) {
	q := t.Model + "Include"
	p("// %s refines an included %q fetch.", q, t.SQLName)
	p("type %s struct {", q)
	p("\tinc lir.Include")
	p("\tfilters []lir.Expr")
	p("}")
	p("")
	p("func (b *%s) filter() lir.Expr {", q)
	p("\tif len(b.filters) == 1 {")
	p("\t\treturn b.filters[0]")
	p("\t}")
	p("\tif len(b.filters) > 1 {")
	p("\t\treturn lir.And{Exprs: b.filters}")
	p("\t}")
	p("\treturn nil")
	p("}")
	p("")

	emitFilterMethods(p, t, q, "b", "b.filters = append(b.filters, %s)")

	for _, c := range t.Cols {
		p("func (b *%s) OrderBy%s() *%s {", q, c.Field, q)
		p("\tb.inc.OrderBy = append(b.inc.OrderBy, lir.OrderTerm{Column: %q})", c.SQLName)
		p("\treturn b")
		p("}")
		p("func (b *%s) OrderBy%sDesc() *%s {", q, c.Field, q)
		p("\tb.inc.OrderBy = append(b.inc.OrderBy, lir.OrderTerm{Column: %q, Desc: true})", c.SQLName)
		p("\treturn b")
		p("}")
	}
	p("func (b *%s) Limit(n int) *%s { b.inc.Limit = n; return b }", q, q)
	p("")

	// Nested includes on include builders.
	for _, r := range t.Forward {
		p("func (b *%s) Include%s(opts ...func(*%sInclude)) *%s {", q, r.Field, r.Target.Model, q)
		p("\tnested := &%sInclude{inc: lir.Include{FK: %q, Dir: lir.ToParent, As: %q}}", r.Target.Model, r.FKName, r.As)
		p("\tfor _, o := range opts {")
		p("\t\to(nested)")
		p("\t}")
		p("\tb.inc.Include = append(b.inc.Include, nested.inc)")
		p("\treturn b")
		p("}")
	}
	for _, r := range t.Reverse {
		p("func (b *%s) Include%s(opts ...func(*%sInclude)) *%s {", q, r.Field, r.Target.Model, q)
		p("\tnested := &%sInclude{inc: lir.Include{FK: %q, Dir: lir.ToChildren, As: %q}}", r.Target.Model, r.FKName, r.As)
		p("\tfor _, o := range opts {")
		p("\t\to(nested)")
		p("\t}")
		p("\tnested.inc.Filter = nested.filter()")
		p("\tb.inc.Include = append(b.inc.Include, nested.inc)")
		p("\treturn b")
		p("}")
	}
	p("")
}

// emitConverters writes lir.Row/Record -> model decoding.
func emitConverters(p func(string, ...any), t *genTable) {
	fn := lowerFirst(t.Model)
	p("func %sFromRow(row lir.Row) %s {", fn, t.Model)
	p("\tm := %s{}", t.Model)
	for _, c := range t.Cols {
		if c.Nullable {
			p("\tm.%s = %sPtr(row[%q])", c.Field, c.GoType, c.SQLName)
		} else {
			p("\tm.%s = row[%q].%s", c.Field, c.SQLName, lirField(c.Type))
		}
	}
	p("\treturn m")
	p("}")
	p("")
	p("func %sFromRecord(rec *frontend.Record) %s {", fn, t.Model)
	p("\tm := %sFromRow(rec.Columns)", fn)
	for _, r := range t.Forward {
		p("\tif parent := rec.Parents[%q]; parent != nil {", r.As)
		p("\t\tv := %sFromRecord(parent)", lowerFirst(r.Target.Model))
		p("\t\tm.%s = &v", r.Field)
		p("\t}")
	}
	for _, r := range t.Reverse {
		p("\tfor _, kid := range rec.Children[%q] {", r.As)
		p("\t\tm.%s = append(m.%s, %sFromRecord(kid))", r.Field, r.Field, lowerFirst(r.Target.Model))
		p("\t}")
	}
	p("\treturn m")
	p("}")
	p("")
}
